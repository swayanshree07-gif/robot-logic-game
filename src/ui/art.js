/** Check a sprite: rectangular, known palette characters. Returns problems. */
export function spriteProblems(rows, palette = PALETTE) {
  const out = [];
  if (!rows.length) return ['empty sprite'];
  const w = rows[0].length;
  rows.forEach((r, y) => {
    if (r.length !== w) out.push(`row ${y} has width ${r.length}, expected ${w}`);
    for (const ch of r) if (ch !== '.' && !(ch in palette)) out.push(`row ${y}: unknown colour '${ch}'`);
  });
  return out;
}

/** Visit every opaque pixel: fn(x, y, colour). */
export function eachPixel(rows, fn, palette = PALETTE) {
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) if (r[x] !== '.') fn(x, y, palette[r[x]]);
  });
}

/**
 * Board layout on a canvas: cell size in screen pixels (a multiple of ART_PX
 * when there's room, so the pixel art scales by a whole number) and the
 * top-left offset that centres the board.
 */
export function layout(world, cw, ch) {
  let cell = Math.floor(Math.min(cw / world.width, ch / world.height));
  if (cell >= ART_PX * 2) cell -= cell % ART_PX;
  cell = Math.max(1, cell);
  return {
    cell,
    scale: cell / ART_PX,
    ox: Math.floor((cw - cell * world.width) / 2),
    oy: Math.floor((ch - cell * world.height) / 2),
  };
}

/** Deterministic 0..1 hash of a tile position (decoration variety without randomness). */
export function tileHash(x, y, seed = 0) {
  let h = (x * 374761393 + y * 668265263 + seed * 2147483647) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
}

/**
 * Which neighbours of a wall tile are also walls: bit 1 N, 2 E, 4 S, 8 W.
 * Outside the map counts as wall.
 */
export function wallMask(world, x, y) {
  let m = 0;
  DIRS.forEach((d, i) => { if (world.tile(x + d.dx, y + d.dy) === 'wall') m |= 1 << i; });
  return m;
}

export const easeInOut = (t) => (t < 0.5 ? 2 * t * t : 1 - (-2 * t + 2) ** 2 / 2);
export const lerp = (a, b, t) => a + (b - a) * t;

/** Tween length for a speed (ms between ticks): most of the gap, capped; 0 = snap. */
export function tweenMs(tickMs, reducedMotion = false) {
  if (reducedMotion || tickMs < 50) return 0;
  return Math.min(Math.round(tickMs * 0.8), 320);
}

/**
 * Smoothly animates Pip between the discrete world states.
 * Call sync(world, ms) after the world may have changed (it reads new
 * world.log events), update(dt) every frame, and pose() to draw.
 * A new world object (reset / new run) snaps to its start position.
 */
export class Animator {
  /** @param {number} [index] which robot to follow (crews: one Animator per robot) */
  constructor(index = 0) { this.world = null; this.index = index; }

  bot(world) { return (world.robots && world.robots[this.index]) || world.robot; }

  snap(world) {
    const r = this.bot(world);
    this.world = world;
    this.seen = world.log.length;
    this.from = { x: r.x, y: r.y };
    this.to = { x: r.x, y: r.y };
    this.dir = r.dir;
    this.prevDir = r.dir;
    this.t = 1; this.dur = 0;
    this.kind = 'idle';
    this.bumpTo = null;
  }

  sync(world, ms = 0) {
    if (world !== this.world) { this.snap(world); return; }
    if (world.log.length === this.seen) return;
    const events = world.log.slice(this.seen);
    this.seen = world.log.length;
    const cur = this.position();
    const r = this.bot(world);
    let last = events[events.length - 1];
    if (world.robots && world.robots.length > 1) {
      // crews: this robot's own change this round (others may have acted)
      const moved = r.x !== this.to.x || r.y !== this.to.y, turned = r.dir !== this.dir;
      const crash = events.find((e) => e.type === 'crash' && e.robot === this.index);
      if (!moved && !turned && !crash) return;
      last = crash ? { type: 'bump', x: crash.x, y: crash.y } : { type: turned && !moved ? 'turn' : 'move' };
    }
    this.from = cur;
    this.to = { x: r.x, y: r.y };
    this.prevDir = this.dir;
    this.dir = r.dir;
    this.kind = last.type;
    this.bumpTo = last.type === 'bump' ? { x: last.x, y: last.y } : null;
    this.dur = last.type === 'bump' ? Math.max(ms, 240) : ms;
    this.t = this.dur > 0 ? 0 : 1;
  }

  update(dt) {
    if (this.t >= 1) return false;
    this.t = Math.min(1, this.t + dt / this.dur);
    return true;
  }

  get busy() { return this.t < 1; }

  position() {
    const k = easeInOut(this.t);
    let x = lerp(this.from.x, this.to.x, k);
    let y = lerp(this.from.y, this.to.y, k);
    if (this.bumpTo && this.t < 1) {
      // lurch a quarter tile toward the wall and spring back
      const p = Math.sin(Math.PI * this.t) * 0.25;
      x += (this.bumpTo.x - this.to.x) * p;
      y += (this.bumpTo.y - this.to.y) * p;
    }
    return { x, y };
  }

  /**
   * What to draw: tile-unit position, which facing sprite, a little vertical
   * hop while turning (pixels in art units) and whether a bump is showing.
   */
  pose() {
    const { x, y } = this.position();
    const turning = this.kind === 'turn' && this.t < 1;
    return {
      x, y,
      dir: turning && this.t < 0.5 ? this.prevDir : this.dir,
      hop: turning ? Math.round(Math.sin(Math.PI * this.t) * 2) : 0,
      bumping: !!this.bumpTo && this.t < 1,
    };
  }
}
