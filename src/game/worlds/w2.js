// World 2 — "Sensor Calibration". Pip's sensors come online, and every level
// is checked on several test floors (`floors`): a fixed list of moves that
// fits one floor fails on the next, so the program has to *look*.
//   1 while + bin (deliver to a bin at an unknown distance)   2 clear + goal: drive to the wall, turn
//   3 if + item (grab only where parts are)   4 if/elif/else + clear_right (winding duct)
//   5 paint codes red/blue in an open room    6 shuttle: whiles inside a repeat
//   7 clear_left alcoves + holding (unload all)   8 finale: paint route, pick-ups, bin
// Every solution must win on every floor (test/world2.test.js, plus randomised
// floors). `par`: steps = the solution's steps on floor 1 (the best *general*
// program we know; a hard-coded route can be shorter on one floor but fails the
// others), size = the solution's size.
// Why 2-1 is a delivery and not "reach the pad": reaching a pad ends the run
// even in the middle of `move N`, so on a straight hall `move <longest>` would
// beat every floor without sensing. Passing over a bin doesn't count, so it does.
