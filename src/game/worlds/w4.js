// World 4 — "Maze Wing". Path planning in the old storage wing.
//   1 right-hand rule: wall following solves any tree maze
//   2 a full wall-following sweep: grab every part, end where you started
//   3 left-hand rule (only the left range finder works)
//   4 wall following inside a routine: fetch a part from the stacks, bring it back
//   5 Pledge algorithm: hold a heading, count turns in a register to get round
//      obstacles (plain wall following circles forever in an open room)
//   6 `scan` comes online: follow the planner through a maze with loops,
//      where wall following goes round in circles
//   7 scan + gripper: deliver every part by shortest routes
//   8 finale: deliver all parts, then reach the pad, on a tight battery that
//      wall following can't afford
// Levels with `floors` are checked on every floor (test/world4.test.js), and
// the full-rules solver must agree each floor is solvable within the solution's steps.
